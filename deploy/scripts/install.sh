#!/usr/bin/env bash
# One-command install of humanoid_arc_bme.onboard.runtime's dependencies ON the G1 dev computer (Jetson Orin NX, JetPack 6.2, Ubuntu 22.04).
#
#   bash deploy/scripts/install.sh [--dry-run] [--ort cpu|gpu]
#
# Writes ONLY to $G1_HOME (default ~/g1_deps: cyclonedds source/build, unitree_sdk2_python checkout, env.sh, install-lock.txt)
# and the venv $G1_VENV (default ~/g1_venv, created with --system-site-packages so ROS 2's rclpy stays importable).
# No sudo, no apt, no system file, no network setting, no service is touched; nothing is sent to the robot.
# Missing system tools are reported with the apt line for YOU to run. Re-running is safe (steps that are done are skipped).
set -euo pipefail
REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
G1_HOME="${G1_HOME:-$HOME/g1_deps}"
G1_VENV="${G1_VENV:-$HOME/g1_venv}"
CYCLONEDDS_REF="${CYCLONEDDS_REF:-releases/0.10.x}"   # the branch unitree_sdk2_python's README builds (OPENED)
SDK_REF="${SDK_REF:-814556d}"                        # unitree_sdk2_python master head seen 2026-10-30 (commits page OPENED); override to pin another
ORT="cpu"; DRY=0
while [ $# -gt 0 ]; do
  case "$1" in
    --dry-run) DRY=1 ;;
    --ort) ORT="$2"; shift ;;
    -h|--help) sed -n '2,12p' "$0"; exit 0 ;;
    *) echo "unknown argument $1"; exit 2 ;;
  esac; shift
done
run() { echo "+ $*"; if [ "$DRY" = 0 ]; then "$@"; fi; }

echo "== humanoid_arc_bme.onboard.runtime install: repo $REPO, deps $G1_HOME, venv $G1_VENV, onnxruntime=$ORT, dry-run=$DRY"
[ "$(uname -m)" = "aarch64" ] || echo "WARNING: not aarch64 ($(uname -m)); this script targets the Jetson"
missing=()
for t in python3 git cmake make gcc g++; do command -v "$t" >/dev/null || missing+=("$t"); done
python3 -c "import venv, ensurepip" 2>/dev/null || missing+=("python3-venv")
python3 -c "import sysconfig, os; assert os.path.exists(os.path.join(sysconfig.get_paths()['include'], 'Python.h'))" 2>/dev/null || missing+=("python3-dev")
if [ ${#missing[@]} -gt 0 ]; then
  echo "MISSING: ${missing[*]}"
  echo "Run yourself (needs sudo, changes the system):  sudo apt-get install -y python3-venv python3-dev cmake build-essential git"
  exit 1
fi
PYV="$(python3 -c 'import sys; print(f"{sys.version_info[0]}.{sys.version_info[1]}")')"
[ "$PYV" = "3.10" ] || echo "WARNING: python $PYV; the pinned wheels were checked for cp310 (JetPack 6.2 / Ubuntu 22.04)"

run mkdir -p "$G1_HOME"
# 1. venv
if [ ! -x "$G1_VENV/bin/python" ]; then run python3 -m venv --system-site-packages "$G1_VENV"; fi
PY="$G1_VENV/bin/python"
run "$PY" -m pip install --upgrade "pip<25" wheel "setuptools<70"
# 2. pinned wheels
run "$PY" -m pip install -r "$REPO/deploy/scripts/requirements-jetson.txt"
if [ "$ORT" = "gpu" ]; then
  run "$PY" -m pip uninstall -y onnxruntime
  run "$PY" -m pip install onnxruntime-gpu==1.24.0 --index-url https://pypi.jetson-ai-lab.io/jp6/cu126
fi
# 3. CycloneDDS C library 0.10.x (from source, as unitree_sdk2_python's README says)
CDDS="$G1_HOME/cyclonedds"
if [ ! -f "$CDDS/install/lib/libddsc.so" ] && [ ! -f "$CDDS/install/lib/aarch64-linux-gnu/libddsc.so" ]; then
  [ -d "$CDDS/.git" ] || run git clone --depth 1 -b "$CYCLONEDDS_REF" https://github.com/eclipse-cyclonedds/cyclonedds "$CDDS"
  run mkdir -p "$CDDS/build" "$CDDS/install"
  run cmake -S "$CDDS" -B "$CDDS/build" -DCMAKE_INSTALL_PREFIX="$CDDS/install" -DBUILD_EXAMPLES=OFF -DBUILD_TESTING=OFF
  run cmake --build "$CDDS/build" --target install -j"$(nproc)"
fi
export CYCLONEDDS_HOME="$CDDS/install"
# 4. python cyclonedds 0.10.2 against it (no aarch64 wheel on PyPI: sdist build)
run "$PY" -m pip install --no-binary cyclonedds cyclonedds==0.10.2
# 5. unitree_sdk2_python at a recorded commit, without its dependency list (opencv-python is not needed by our imports)
SDK="$G1_HOME/unitree_sdk2_python"
[ -d "$SDK/.git" ] || run git clone https://github.com/unitreerobotics/unitree_sdk2_python.git "$SDK"
run git -C "$SDK" fetch --all --tags
run git -C "$SDK" checkout "$SDK_REF"
run "$PY" -m pip install --no-deps -e "$SDK"
# 6. environment file used by run.sh / preflight.sh / build.sh
if [ "$DRY" = 0 ]; then
  cat > "$G1_HOME/env.sh" <<ENV
# generated by deploy/scripts/install.sh $(date -Iseconds)
source "$G1_VENV/bin/activate"
export CYCLONEDDS_HOME="$CDDS/install"
export G1_REPO="$REPO"
ENV
  {
    echo "# install lock $(date -Iseconds) on $(hostname)"
    echo "repo $(git -C "$REPO" rev-parse HEAD 2>/dev/null || echo unknown) dirty=$(git -C "$REPO" status --porcelain 2>/dev/null | wc -l)"
    echo "cyclonedds_c $(git -C "$CDDS" rev-parse HEAD 2>/dev/null || echo unknown) ($CYCLONEDDS_REF)"
    echo "unitree_sdk2_python $(git -C "$SDK" rev-parse HEAD 2>/dev/null || echo unknown)"
    "$PY" -m pip freeze
  } > "$G1_HOME/install-lock.txt"
  echo "wrote $G1_HOME/env.sh and $G1_HOME/install-lock.txt"
fi
# 7. read-only checks (versions, network, disk, clock); exits non-zero if something required is missing
echo "== preflight (read-only)"
if [ "$DRY" = 0 ]; then (cd "$REPO" && "$PY" -m humanoid_arc_bme.onboard.runtime preflight) || echo "preflight reported problems (see above)"; fi
echo "== done. Next: bash deploy/scripts/test.sh, then bash deploy/scripts/preflight.sh --iface <if> --listen 3"
